#!/usr/bin/env node
// Bar 2 of the store release (docs/plans/STORE_RELEASE.md): no retired layout ships.
//
//   npx tsx scripts/track-originality.mjs [--write] [--json]
//
// Every ROCKHOP course (src/tracks/rockhop: the twelve tracks and the four zone playgrounds) against every retired
// course (the 15-track curriculum, the five `p<n>-*` playgrounds, the Labs): the normalised cross-correlation of
// the two SILHOUETTES (the top of every rideable surface along x, sampled every 0.5 m start -> finish), maximised
// over lags — in metres (overlap >= 60 % of the LONGER course: a re-skin keeps most of a layout) and stretched end to end (512 points, lags up to
// +-20 %); the score is the larger. The definition lives in src/tracks/rockhop/originality.ts (the rockhop test
// gates the same numbers). A score >= 0.6 fails (exit 1).
//
// --write puts the table and the full matrix under docs/evidence/store-release/tracks/originality.{md,json}.
// Runs under tsx because the tracks are TypeScript.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileTrack, RETIRED_TRACKS, ROCKHOP_ALL } from '../src/tracks/index.ts';
import { originality, ORIGINALITY_LIMIT } from '../src/tracks/rockhop/originality.ts';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const write = args.has('--write');
const asJson = args.has('--json');

const retired = RETIRED_TRACKS.map((t) => compileTrack(t));
const fresh = ROCKHOP_ALL.map((t) => compileTrack(t));

const rows = [];
for (const a of fresh) {
  const cells = retired.map((b) => {
    const o = originality(a, b);
    return { retired: b.def.id, score: round(o.score), metric: round(o.metric.r), metricLagM: o.metric.lag * 0.5, stretched: round(o.stretched.r) };
  });
  cells.sort((x, y) => y.score - x.score);
  rows.push({ id: a.def.id, name: a.def.name, code: a.def.meta?.code ?? '', max: cells[0].score, closest: cells[0].retired, pass: cells[0].score < ORIGINALITY_LIMIT, cells });
}
// the new set against itself: not a bar, a readability check (two new tracks should not be one layout twice)
const internal = [];
for (let i = 0; i < fresh.length; i++) {
  for (let j = i + 1; j < fresh.length; j++) internal.push({ a: fresh[i].def.id, b: fresh[j].def.id, score: round(originality(fresh[i], fresh[j]).score) });
}
internal.sort((x, y) => y.score - x.score);

const fails = rows.filter((r) => !r.pass);
const md = [
  '# Track originality (store release bar 2)',
  '',
  `Generated by \`npx tsx scripts/track-originality.mjs --write\`. Limit: every new course < ${ORIGINALITY_LIMIT} against every retired course.`,
  'Score = max over lags of the Pearson correlation of the two silhouettes (top of every rideable surface, 0.5 m samples),',
  'in metres (overlap >= 60 % of the longer course) and stretched end to end (512 points, lags +-20 %), the larger of the two.',
  `Retired set: ${retired.length} courses (curriculum, p1-p5 playgrounds, labs). New set: ${fresh.length} courses.`,
  '',
  '| code | track | max r | closest retired | metric r | stretched r | 2nd closest | pass |',
  '|---|---|---:|---|---:|---:|---|---|',
  ...rows.map((r) => `| ${r.code} | ${r.id} | ${r.max.toFixed(3)} | ${r.closest} | ${r.cells[0].metric.toFixed(3)} | ${r.cells[0].stretched.toFixed(3)} | ${r.cells[1].retired} ${r.cells[1].score.toFixed(3)} | ${r.pass ? 'yes' : '**NO**'} |`),
  '',
  `Worst pair overall: ${rows.reduce((a, b) => (b.max > a.max ? b : a)).id} vs ${rows.reduce((a, b) => (b.max > a.max ? b : a)).closest} at ${Math.max(...rows.map((r) => r.max)).toFixed(3)}.`,
  '',
  '## New set against itself (not a bar: no two new courses should be one layout twice)',
  '',
  '| a | b | r |',
  '|---|---|---:|',
  ...internal.slice(0, 8).map((p) => `| ${p.a} | ${p.b} | ${p.score.toFixed(3)} |`),
  '',
].join('\n');

if (asJson) console.log(JSON.stringify({ limit: ORIGINALITY_LIMIT, rows, internal }, null, 2));
else console.log(md);
if (write) {
  const dir = join(repo, 'docs', 'evidence', 'store-release', 'tracks');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'originality.md'), md);
  writeFileSync(join(dir, 'originality.json'), `${JSON.stringify({ limit: ORIGINALITY_LIMIT, retired: retired.map((t) => t.def.id), rows, internal }, null, 2)}\n`);
}
if (fails.length) {
  console.error(`track-originality: ${fails.length} course(s) at or above ${ORIGINALITY_LIMIT}: ${fails.map((f) => `${f.id} ~ ${f.closest} ${f.max}`).join(', ')}`);
  process.exit(1);
}

function round(v) {
  return Math.round(v * 1000) / 1000;
}
